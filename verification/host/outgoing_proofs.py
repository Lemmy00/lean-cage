#!/usr/bin/env python3
"""Check outgoing projections of the maintained source decomposition proofs.

The generator is untrusted: every generated declaration is checked by Rocq.
No source, primitive contract, host run or successful-return premise is replaced.
The only additional premise is that the stream's two actual FDs differ.
"""
# §AR-host-boundary.interfaces: Reuse the maintained source cuts for outgoing traces.
import hashlib
import importlib.util
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WORK = ROOT / '.tools/host/gateway'
NAMES = '''PrimitiveCalls PollStorePath GuardObservation InertCuts InertEffects ScopedBufferRuntime
CancellationAfterSend CancellationBuffers CancellationComplete CancellationEntryBuffers
CancellationPathBuffers CancellationReturnBuffers CancellationSend CancellationSendBuffers CancellationSuffix
ClockBufferOperation ClockBuffers ClockComplete
ReadyCapture ReadyClock ReadyComplete ReadyControl ReadyEntry ReadyHelpers ReadyIteration ReadyLoop
ReadyNoOutput ReadyOperations ReadyReturn ReadySetup ReadySignals ReadyTail ReadyTimeout'''.split()
MAPPING = {'Gateway' + name: 'GatewayOutgoing' + name for name in NAMES}


def generate():
    inputs = {}
    for old, new in MAPPING.items():
        path = HERE / (old + '.v')
        source = path.read_text()
        inputs[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
        for previous, following in MAPPING.items():
            source = re.sub(r'\b' + previous + r'\b', following, source)
        source = source.replace('received', 'sent')
        source = source.replace('gateway_actual_primitive_no_receive', 'gateway_actual_primitive_no_send')
        # The same source cuts use the outgoing event projection. All primitive
        # shapes are checked again, including the real cancellation send below.
        start = source.index('Import ListNotations.')
        source = source[:start] + 'From HostGateway Require Import GatewaySendRuntime GatewaySendChannels.\n' + source[start:]
        if old in ('GatewayCancellationSend', 'GatewayCancellationSendBuffers'):
            marker = 'Variables (reference : mem) (owner : World).'
            if marker not in source:
                marker = '(data_block : block) (data_offset : ptrofs) (amount : Z) (readonly : block -> Z -> Prop).'
            assert marker in source
            source = source.replace(marker, marker + '\nContext {outgoing_channels : gateway_distinct_channels initial}.', 1)
            needle = 'unfold gateway_sent_event; rewrite IO; reflexivity.'
            assert source.count(needle) == 1
            source = source.replace(needle,
                'unfold gateway_sent_event; rewrite IO.\n'
                '  rewrite Int.eq_false; [reflexivity | intro SAME; apply gateway_channels_distinct; symmetry; exact SAME].')
        elif old in ('GatewayCancellationComplete', 'GatewayReadyHelpers', 'GatewayReadyControl', 'GatewayReadyLoop'):
            marker = 'Variables (reference : mem) (owner : World).'
            assert marker in source
            source = source.replace(marker, marker + '\nContext {outgoing_channels : gateway_distinct_channels initial}.', 1)
        elif old == 'GatewayReadyComplete':
            marker = 'amount readonly direction before world events after next :'
            assert marker in source
            source = source.replace(marker, marker[:-1] + '\n    {outgoing_channels : gateway_distinct_channels initial} :', 1)
        if old == 'GatewayReadyHelpers':
            marker = 'intros CONTROL CANCEL SEND_SYMBOL SEND_FUNCTION ERRNO_SYMBOL ERRNO_FUNCTION READY RUN.'
            assert marker in source
            source = source.replace(marker, marker + '\n  assert (CURRENT_CHANNELS : gateway_distinct_channels current).\n'
                '  { eapply gateway_distinct_channels_retained; [exact outgoing_channels | exact (proj1 (proj2 READY))]. }\n'
                '', 1)
        source = '(* Generated by verification/host/outgoing_proofs.py; kernel checking is required. *)\n' + source
        (WORK / (new + '.v')).write_text(source)
    (WORK / 'outgoing-inputs.json').write_text(json.dumps(inputs, indent=2, sort_keys=True) + '\n')


def main():
    generate()
    spec = importlib.util.spec_from_file_location('outgoing_gateway', HERE / 'gateway.py')
    gateway = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gateway)
    pending = set(MAPPING.values())
    while pending:
        available = sorted(name for name in pending if not any(
            re.search(r'\b' + dependency + r'\b', (WORK / (name + '.v')).read_text())
            for dependency in pending - {name}))
        if not available:
            raise RuntimeError('outgoing source-cut dependency cycle')
        for name in available:
            gateway.compile_file(name)
            pending.remove(name)


if __name__ == '__main__':
    main()
