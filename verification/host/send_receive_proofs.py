#!/usr/bin/env python3
"""Kernel-check the no-receive projection of the maintained outgoing source cuts.

The generator is untrusted. It preserves actual source runs, errors, retries,
primitive contracts and payload/count premises; only the observation result is
changed. Every emitted proof is checked by the ordinary strict Rocq profile.
"""
# §AR-host-boundary.interfaces.gateway: Reuse real sender decompositions for the receive queue.
import argparse
import hashlib
import json

import gateway


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError("maintained sender projection anchor changed: " + old[:100])
    return source.replace(old, new, 1)


def generate():
    iteration_path = gateway.HERE / "GatewaySendIteration.v"
    count_path = gateway.HERE / "GatewaySendCount.v"
    iteration = iteration_path.read_text()
    iteration = iteration.replace("actual_restored_send_prefix", "actual_restored_send_no_receive_prefix")
    iteration = iteration.replace("actual_send_iteration_from_ready", "actual_send_no_receive_iteration")
    iteration = replace_once(iteration,
        "gateway_sent_bytes io(stream_descriptor initial)prefix=bytes /\\",
        "gateway_received_bytes io(stream_descriptor initial)prefix=[] /\\")
    start = iteration.index("      * assert(B0:")
    end = iteration.index("      * split;[exact COUNT|]", start)
    projection = iteration[start:end]
    projection = projection.replace("gateway_sent_bytes", "gateway_received_bytes")
    projection = projection.replace("gateway_quiet_sent_empty", "gateway_quiet_received_empty")
    projection = projection.replace("gateway_actual_primitive_no_send", "gateway_actual_primitive_no_receive")
    projection = replace_once(projection,
        "rewrite B0,BSAVE,B1,SEND_BYTES,B2,BERRNO,BC;cbn[app].\n"
        "        change(bytes++gateway_received_bytes io(stream_descriptor initial)((p3++restore_events)++p4)=bytes).\n"
        "        repeat rewrite gateway_received_bytes_append;rewrite B3,BRESTORE,B4;cbn;apply app_nil_r.",
        "rewrite B0,BSAVE,B1,NO_RECEIVE,B2,BERRNO,BC;cbn[app].\n"
        "        change(gateway_received_bytes io(stream_descriptor initial)((p3++restore_events)++p4)=[]).\n"
        "        repeat rewrite gateway_received_bytes_append;rewrite B3,BRESTORE,B4;reflexivity.")
    iteration = iteration[:start] + projection + iteration[end:]
    count = count_path.read_text()
    count = count.replace("GatewaySendIteration", "GatewaySendNoReceiveIteration")
    count = count.replace("actual_send_iteration_from_ready", "actual_send_no_receive_iteration")
    for old, new in [("actual_send_loop_count_bounded", "actual_send_no_receive_loop_bounded"),
                     ("actual_send_loop_count", "actual_send_no_receive_loop"),
                     ("actual_send_transfer_count", "actual_send_no_receive_transfer")]:
        count = count.replace(old, new)
    count = replace_once(count,
        "Context(ready_no_send:gateway_ready_no_data_send_source backend ge io native_private stable_readonly(discipline None)).\n", "")
    ready_start = count.index("    pose proof(ready_no_send")
    ready_end = count.index("    destruct(ready_source", ready_start)
    count = count[:ready_start] + count[ready_end:]
    count = count.replace("Z.of_nat(length(gateway_sent_bytes io(stream_descriptor initial)events))=size",
                          "gateway_received_bytes io(stream_descriptor initial)events=[]")
    count = count.replace("gateway_sent_bytes", "gateway_received_bytes")
    count = count.replace("gateway_quiet_sent_empty", "gateway_quiet_received_empty")
    count = count.replace("iprefix=bytes", "iprefix=[]")
    count = count.replace("READY_SENT", "READY_BYTES")
    count = replace_once(count,
        "rewrite READY_PREFIX_BYTES,READY_BYTES,ITER_BYTES,REST_BYTES;cbn;rewrite app_nil_r,BYTES.\n"
        "           subst count;rewrite Z.max_r by lia;reflexivity.",
        "rewrite READY_PREFIX_BYTES,READY_BYTES,ITER_BYTES,REST_BYTES;reflexivity.")
    count = replace_once(count,
        "rewrite READY_PREFIX_BYTES,READY_BYTES,ITER_BYTES,ADVANCE_BYTES;cbn.\n"
        "           rewrite length_app,Nat2Z.inj_add,BYTES,REST_COUNT,Z.max_r by lia;lia.",
        "rewrite READY_PREFIX_BYTES,READY_BYTES,ITER_BYTES,ADVANCE_BYTES,REST_COUNT;reflexivity.")
    count = replace_once(count,
        "rewrite READY_PREFIX_BYTES,READY_BYTES,ITER_BYTES,ADVANCE_BYTES;cbn.\n"
        "        rewrite length_app,Nat2Z.inj_add,BYTES,REST_COUNT;cbn;lia.",
        "rewrite READY_PREFIX_BYTES,READY_BYTES,ITER_BYTES,ADVANCE_BYTES,REST_COUNT;reflexivity.")
    generated = {"GatewaySendNoReceiveIteration": iteration, "GatewaySendNoReceiveCount": count}
    header = "(* Generated by verification/host/send_receive_proofs.py; kernel checking is required. *)\n"
    for name, source in generated.items():
        (gateway.WORK / (name + ".v")).write_text(header + source)
    inputs = [iteration_path, count_path, gateway.HERE / "send_receive_proofs.py"]
    record = {"inputs": {str(path.relative_to(gateway.ROOT)): gateway.sha(path) for path in inputs},
              "generated": {name: gateway.sha(gateway.WORK / (name + ".v")) for name in generated}}
    (gateway.WORK / "send-receive-inputs.json").write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate-only", action="store_true")
    arguments = parser.parse_args()
    generated = generate()
    if not arguments.generate_only:
        for name in generated:
            gateway.compile_file(name)


if __name__ == "__main__":
    main()
